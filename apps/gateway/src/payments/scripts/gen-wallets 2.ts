// Generates testnet wallets: one payer (gateway) and one payee per merchant plus the attacker.
// Private keys are appended to the repo-root .env (gitignored); existing keys are never overwritten.
// Payee addresses are public and written to apps/merchants/payees.json for the catalog.
// Prints addresses only, never keys.
import { appendFileSync, chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseEnv } from 'node:util';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';

const repoRoot = resolve(import.meta.dirname, '../../../../..');
const envPath = resolve(repoRoot, '.env');
const payeesPath = resolve(repoRoot, 'apps/merchants/payees.json');

const wallets = [
  { name: 'payer', envVar: 'WALLET_PRIVATE_KEY' },
  { name: 'pricescope', envVar: 'PAYEE_PRICESCOPE_PRIVATE_KEY' },
  { name: 'skydata', envVar: 'PAYEE_SKYDATA_PRIVATE_KEY' },
  { name: 'newswire', envVar: 'PAYEE_NEWSWIRE_PRIVATE_KEY' },
  { name: 'attacker', envVar: 'PAYEE_ATTACKER_PRIVATE_KEY' },
] as const;

const existing = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
const addresses: Record<string, string> = {};
const appended: string[] = [];

for (const w of wallets) {
  let key = existing[w.envVar] as `0x${string}` | undefined;
  const isNew = !key;
  if (!key) {
    key = generatePrivateKey();
    appended.push(`${w.envVar}=${key}`);
  }
  addresses[w.name] = privateKeyToAccount(key).address.toLowerCase();
  console.log(`${w.name.padEnd(10)} ${addresses[w.name]}  (${isNew ? 'new' : 'existing'})`);
}

if (appended.length > 0) {
  const created = !existsSync(envPath);
  const prefix = created || readFileSync(envPath, 'utf8').endsWith('\n') ? '' : '\n';
  appendFileSync(
    envPath,
    `${prefix}# Testnet wallets (Base Sepolia only) generated by payments:wallets\n${appended.join('\n')}\n`,
  );
  if (created) chmodSync(envPath, 0o600);
}

const { payer, ...payees } = addresses;
writeFileSync(payeesPath, JSON.stringify({ network: 'eip155:84532', payees }, null, 2) + '\n');
console.log(`\nPayer address (fund this): ${payer}`);
